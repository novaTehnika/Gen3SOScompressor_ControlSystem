function proc = sopProcedure()
%SOPPROCEDURE The procedure the operator app walks through in non-manual mode.
%   proc = sopProcedure()
%
%   Data only; the engine (master-src/logic/proc*.m) holds no procedure of
%   its own. The steps are a placeholder named after the operator app's
%   earlier stub tabs until the SOP exists: a step with a target takes its
%   target from the SOP, and the instructions are to be replaced by the
%   SOP's. To use another procedure, edit this file or add a file beside it
%   and set cfg.procedure in masterConfig.m. procNew validates the result;
%   tests/smokeProcedureEngine.m runs it through procNew.
%
%   See the "Procedure (non-manual mode)" section of master-src/README.md
%   for the fields of a parameter and of a step.

cfg = masterConfig();

% ----- Parameters (Process Parameters tab) -----
params = {
    struct('key', 'salineVolume', 'label', 'Total Solution Volume', ...
        'unit', 'mL', 'value', cfg.salineVolume, 'min', cfg.deadVolume, ...
        'max', x2mL(cfg.posMin, cfg))
    struct('key', 'oxygenLoadPressure', 'label', 'Oxygen Loading Pressure', ...
        'unit', 'psi', 'value', 100, 'min', 0, 'max', 3000)
    struct('key', 'dischargePressure', 'label', 'Discharge Pressure', ...
        'unit', 'atm', 'value', 5, 'min', cfg.atmAmbient, ...
        'max', cfg.pressureMax * cfg.atmPerMPa + cfg.atmAmbient)
    struct('key', 'henrysLimitPct', ...
        'label', 'Henry''s Limit (at discharge pressure)', ...
        'unit', '%', 'value', 100, 'min', 0, 'max', 100)
    struct('key', 'o2SalineMassRatio', 'label', 'Oxygen-Saline Mass Ratio', ...
        'value', 0, 'min', 0, 'max', Inf)
    struct('key', 'o2SalineVolumeRatio', ...
        'label', 'Oxygen-Saline Volume Ratio (at loading pressure)', ...
        'value', 1, 'min', 0, 'max', Inf)
    struct('key', 'useMixer', 'label', 'Use Mixer', 'value', 1, ...
        'min', 0, 'max', 1, 'format', '%d')
    };

% ----- Steps -----
steps = {
    struct('section', 'Process parameters', 'type', 'param', ...
        'title', 'Set the process parameters', ...
        'text', 'Enter the process parameters, then confirm.', ...
        'params', {{'salineVolume', 'oxygenLoadPressure', ...
        'dischargePressure', 'henrysLimitPct', 'o2SalineMassRatio', ...
        'o2SalineVolumeRatio', 'useMixer'}})
    struct('id', 'purgePrepare', 'section', 'Saline purge/fill', ...
        'type', 'confirm', 'title', 'Prepare the saline purge', ...
        'checks', {{'Insert the saline line into the saline bag', ...
        'Insert the discharge line into an empty saline bag', ...
        'Close all valves', 'Open the saline valve', ...
        'Open the main chamber valve'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw saline', ...
        'text', 'Drawing {salineVolume} mL of saline.', ...
        'op', 'position', 'target', 'salineVolume', 'unit', 'mL')
    struct('type', 'confirm', 'title', 'Purge', ...
        'checks', {{'Close the saline valve', 'Open the discharge valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Purge to end of travel', ...
        'op', 'position', 'target', 0, 'unit', 'mm')
    struct('type', 'confirm', 'title', 'Purge again or fill', ...
        'repeatFrom', 'purgePrepare', 'repeatLabel', 'Repeat Purge', ...
        'confirmLabel', 'Fill Saline')
    struct('type', 'confirm', 'title', 'Prepare the fill', ...
        'checks', {{'Close the discharge valve', 'Open the saline valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Fill saline', ...
        'op', 'position', 'target', 'salineVolume', 'unit', 'mL')
    struct('type', 'confirm', 'title', 'Close the saline valve')
    struct('section', 'Oxygen fill', 'type', 'confirm', ...
        'title', 'Prepare the oxygen fill', ...
        'checks', {{'Close all valves', ...
        'Open the oxygen inlet and main chamber valve', ...
        'Open the oxygen regulator until the pressure reaches 50 psi'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'confirm', 'title', 'Fill oxygen', ...
        'confirmLabel', 'Fill Oxygen')
    struct('type', 'confirm', 'title', 'Finish the oxygen fill', ...
        'checks', {{['Open the oxygen regulator until the pressure ' ...
        'reaches {oxygenLoadPressure} psi'], ...
        'Close the oxygen inlet and main chamber valve', ...
        'Close the oxygen regulator'}}, 'confirmLabel', 'Continue')
    struct('section', 'Pressurize', 'type', 'confirm', ...
        'title', 'Ensure all valves are closed')
    struct('type', 'machine', 'title', 'Pressurize', ...
        'text', 'Holding {dischargePressure} atm.', 'op', 'pressure', ...
        'target', 'dischargePressure', 'until', 'running', 'keep', true, ...
        'timerStart', true, 'mixer', 'useMixer')
    struct('type', 'wait', 'title', 'Pressure settling', 'until', 'settled')
    struct('section', 'Discharge', 'type', 'confirm', ...
        'title', 'Open the main chamber valve', ...
        'text', ['Open the main chamber valve and wait for the pressure ' ...
        'to stabilize.'])
    struct('type', 'confirm', 'title', 'Open the discharge valve', ...
        'text', ['Open the discharge valve and wait for the pressure ' ...
        'to stabilize.'])
    struct('type', 'confirm', 'title', 'Open the valve at the needle', ...
        'text', ['Open the valve at the needle. Confirm when the delivery ' ...
        'is complete; the panel shows the volume discharged.'], ...
        'zeroVolume', true)
    struct('type', 'machine', 'title', 'End pressure control', ...
        'op', 'stop', 'timerStop', true, 'mixer', 'off')
    };

proc = struct('name', 'SOS fill and delivery (seed, pre-SOP)', ...
    'params', {params}, 'steps', {steps}, ...
    'timerLabel', 'Time pressurized', ...
    'volumeLabel', 'Volume discharged (mL)');
end
