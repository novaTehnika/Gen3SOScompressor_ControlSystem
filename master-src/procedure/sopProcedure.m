function proc = sopProcedure()
%SOPPROCEDURE The procedure the operator app walks through in non-manual mode.
%   proc = sopProcedure()
%
%   Data only; the engine (master-src/logic/proc*.m) holds no procedure of
%   its own. The steps are a placeholder until the SOP exists: a step with a
%   target takes its target from the SOP, and the instructions are to be
%   replaced by the SOP's. To use another procedure, edit this file or add a
%   file beside it and set cfg.procedure in masterConfig.m. procNew
%   validates the result; tests/smokeProcedureEngine.m runs it through
%   procNew.
%
%   The fill: a saline purge (draw, then push the air out through the
%   discharge line), the saline fill (draw the volume plus an excess, push
%   the excess back so the chamber holds exactly the saline volume), the
%   oxygen fill (retract to the volume that holds the oxygen at the loading
%   pressure, load it from the regulator) and the pressurize and discharge
%   steps. The saline volume and the oxygen ratio are also written to the
%   slave (sinks), which receives them.
%
%   See the "Procedure (non-manual mode)" section of master-src/README.md
%   for the fields of a parameter and of a step.

cfg = masterConfig();

% ----- Constants -----
FILL_EXCESS = 30;        % mL drawn beyond the saline volume and pushed back, so the fill ends by a purge
PUSH_SPEED = 0.5;        % mm/s of a push against the discharge line (1.7 mL/s) so the flow, and the pressure the line builds, stay low
PUSH_PRESSURE_MAX = 10;  % atm absolute: a push pauses above this (the line is blocked)

% ----- Parameters (Process Parameters tab) -----
params = {
    struct('key', 'salineVolume', ...
        'label', 'Saline volume (chamber, incl. dead volume)', ...
        'unit', 'mL', 'value', cfg.salineVolume, 'min', cfg.deadVolume, ...
        'max', cfg.deadVolume + sweptVolume(cfg.posMin, cfg) - FILL_EXCESS, ...
        'sink', 'SalineVolume')
    struct('key', 'oxygenRatio', ...
        'label', 'Oxygen ratio (STP volume per saline volume)', ...
        'value', cfg.oxygenRatio, 'min', 0, 'max', 4, 'format', '%.2f', ...
        'sink', 'OxygenRatio')
    struct('key', 'oxygenLoadPressure', 'label', 'Oxygen loading pressure', ...
        'kind', 'pressure', 'value', 7.8, 'min', 2, 'max', 14.6)
    struct('key', 'dischargePressure', 'label', 'Discharge pressure', ...
        'kind', 'pressure', 'value', 5, 'min', cfg.atmAmbient, ...
        'max', min(cfg.pressureMax, cfg.pressureCeiling ...
        - cfg.pressureCeilingHyst) * cfg.atmPerMPa + cfg.atmAmbient)
    struct('key', 'purgeVolume', 'label', 'Purge volume (swept)', ...
        'unit', 'mL', 'value', 100, 'min', 1, ...
        'max', sweptVolume(cfg.posMin, cfg))
    struct('key', 'useMixer', 'label', 'Use Mixer', 'value', 1, ...
        'min', 0, 'max', 1, 'format', '%d')
    };

% ----- Steps -----
steps = {
    struct('section', 'Process parameters', 'type', 'param', ...
        'title', 'Set the process parameters', ...
        'text', 'Enter the process parameters, then confirm.', ...
        'params', {{'salineVolume', 'oxygenRatio', 'oxygenLoadPressure', ...
        'dischargePressure', 'purgeVolume', 'useMixer'}})

    % Saline purge
    struct('id', 'purgePrepare', 'section', 'Saline purge', ...
        'type', 'confirm', 'title', 'Prepare the saline purge', ...
        'checks', {{'Insert the saline line into the saline bag', ...
        'Insert the discharge line into an empty bag', ...
        'Close all valves', 'Open the saline valve', ...
        'Open the main chamber valve'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw the purge saline', ...
        'text', 'Drawing {purgeVolume} mL of saline.', ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) c.deadVolume + v.purgeVolume)
    struct('type', 'confirm', 'title', 'Switch to discharge', ...
        'checks', {{'Close the saline valve', 'Open the discharge valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Purge to the end of travel', ...
        'op', 'position', 'unit', 'mm', 'target', 0, ...
        'speed', PUSH_SPEED, 'pressureMax', PUSH_PRESSURE_MAX)
    struct('type', 'confirm', 'title', 'Purge again or fill', ...
        'repeatFrom', 'purgePrepare', 'repeatLabel', 'Repeat Purge', ...
        'confirmLabel', 'Fill Saline')

    % Saline fill
    struct('section', 'Saline fill', 'type', 'confirm', ...
        'title', 'Prepare the fill', ...
        'checks', {{'Close the discharge valve', 'Open the saline valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw the fill', ...
        'text', sprintf('Drawing {salineVolume} mL plus %g mL to purge back.', ...
        FILL_EXCESS), 'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) v.salineVolume + FILL_EXCESS)
    struct('type', 'confirm', 'title', 'Switch to discharge', ...
        'checks', {{'Close the saline valve', 'Open the discharge valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Purge back to the fill volume', ...
        'op', 'position', 'unit', 'mL', 'target', 'salineVolume', ...
        'speed', PUSH_SPEED, 'pressureMax', PUSH_PRESSURE_MAX)
    struct('type', 'confirm', 'title', 'Close the discharge valve')

    % Oxygen fill
    struct('section', 'Oxygen fill', 'type', 'confirm', ...
        'title', 'Prepare the oxygen fill', ...
        'checks', {{'Close all valves', 'Close the oxygen regulator', ...
        'Open the oxygen inlet valve', 'Open the main chamber valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Make room for the oxygen', ...
        'text', ['Retracting to the chamber volume for {oxygenRatio} ' ...
        'volumes of oxygen at {oxygenLoadPressure}.'], ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) oxygenFillVolume(v, c))
    struct('type', 'confirm', 'title', 'Load the oxygen', ...
        'checks', {{['Open the oxygen regulator until the pressure ' ...
        'readout shows {oxygenLoadPressure}'], ...
        'Close the oxygen inlet valve', 'Close the main chamber valve', ...
        'Close the oxygen regulator'}}, 'confirmLabel', 'Continue')

    % Pressurize
    struct('section', 'Pressurize', 'type', 'confirm', ...
        'title', 'Ensure all valves are closed')
    struct('type', 'machine', 'title', 'Pressurize', ...
        'text', 'Holding {dischargePressure}.', 'op', 'pressure', ...
        'target', 'dischargePressure', 'until', 'running', 'keep', true, ...
        'timerStart', true, 'mixer', 'useMixer')
    struct('type', 'wait', 'title', 'Pressure settling', 'until', 'settled')

    % Discharge
    struct('section', 'Discharge', 'type', 'confirm', ...
        'title', 'Open the main chamber valve', ...
        'text', ['Open the main chamber valve and wait for the pressure ' ...
        'to stabilize.'])
    struct('type', 'confirm', 'title', 'Open the discharge valve', ...
        'text', ['Open the discharge valve and wait for the pressure ' ...
        'to stabilize.'])
    struct('type', 'confirm', 'title', 'Open the valve at the needle', ...
        'text', ['Open the valve at the needle. Confirm when the delivery ' ...
        'is complete; the step also ends at the end of travel.'], ...
        'zeroVolume', true, 'alsoWhen', 'endOfTravel', ...
        'confirmLabel', 'Delivery Complete')
    struct('type', 'machine', 'title', 'End pressure control', ...
        'op', 'stop', 'timerStop', true, 'mixer', 'off')
    };

proc = struct('name', 'SOS fill and delivery (seed, pre-SOP)', ...
    'params', {params}, 'steps', {steps}, ...
    'timerLabel', 'Time pressurized', ...
    'volumeLabel', 'Volume discharged (mL)');
end

function V = oxygenFillVolume(v, c)
% Chamber volume for the oxygen fill, mL.
%   V = Vs + r * Vs * (P_STP / P_load) * (T_room / T_STP)     [mL]
% Vs [mL] salineVolume (saline incl. dead volume), r [-] oxygenRatio (STP
% volume per saline volume, STP = 0 degC and 1 atm), P_load [atm abs]
% oxygenLoadPressure, P_STP = 1 atm, T_room = 293.15 K, T_STP = 273.15 K.
% Ideal gas, isothermal at room temperature; dissolution of oxygen in the
% saline during the load is ignored (it only adds to the charge).
P_STP = 1;           % atm
T_ROOM = 293.15;     % K
T_STP = 273.15;      % K
V = v.salineVolume + v.oxygenRatio * v.salineVolume ...
    * (P_STP / v.oxygenLoadPressure) * (T_ROOM / T_STP);
vMax = c.deadVolume + sweptVolume(c.posMin, c);
if V > vMax
    error('sopProcedure:oxygenFill', ['the oxygen fill needs %.0f mL, ' ...
        'more than the chamber holds (%.0f mL)'], V, vMax);
end
end
