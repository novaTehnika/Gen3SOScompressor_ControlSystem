function proc = sopProcedure()
%SOPPROCEDURE The procedure the operator app walks through in non-manual mode.
%   proc = sopProcedure()
%
%   Data only; the engine (master-src/logic/proc*.m) holds no procedure of
%   its own. The steps follow the lab's SOP ("SOS Gen 3 Compressor SOP"),
%   from the reset of a previous experiment to the clean-up; its start-up
%   (power, log-in, opening the app, Connect) comes before Start Procedure.
%   To use another procedure, edit this file or add a file beside it and set
%   cfg.procedure in masterConfig.m. procNew validates the result;
%   tests/smokeProcedureEngine.m runs it through procNew and walks it.
%
%   The sections: the reset (homing, only when the position frame is lost;
%   the operator skips it otherwise), the flush (cycles of a 20 mm saline
%   draw pushed out through the stopcock), the hose (saline pushed out to
%   the needle), the saline fill (the volume plus 5 mm drawn, the 5 mm
%   pushed back out of the stopcock), the oxygen fill (retract 5 mm past the
%   volume that holds the oxygen at the loading pressure and come back to
%   it, load from the regulator at the pressure read, and move again for
%   that pressure), pressurize and mix, discharge and clean-up (rinse with
%   deionized water pushed out under pressure control). The saline volume
%   and the oxygen ratio are also written to the shell's SalineVolume and
%   OxygenRatio blocks (sinks), which the trace records.
%
%   See the "Procedure (non-manual mode)" section of master-src/README.md
%   for the fields of a parameter and of a step.

cfg = masterConfig();

% ----- Constants -----
EXCESS_MM = 5;             % mm drawn past a fill position and pushed back, so the fill ends moving toward the end of travel
PUSH_SPEED = 2;            % mm/s of a push through the stopcock or the hose (6.9 mL/s)
SALINE_PUSH_MAX = 3;       % atm absolute: a push out of the stopcock pauses above this (the outlet is blocked)
HOSE_PUSH_MAX = 10;        % atm absolute: a push through the hose pauses above this (a valve is shut)
FLUSH_DRAW = 20;           % mm from the end of travel of a flush draw
HOSE_DRAW = 30;            % mm from the end of travel of the draw that fills the hose
RINSE_LIMIT = 150;         % mm from the end of travel the rinse draw stops at
RINSE_PRESSURE = 100;      % atm absolute of the rinse push

% ----- Parameters (Process Parameters tab) -----
excessMl = EXCESS_MM * mLPerMm(cfg);
params = {
    struct('key', 'salineVolume', ...
        'label', 'Saline volume (chamber, incl. dead volume)', ...
        'unit', 'mL', 'value', cfg.salineVolume, 'min', cfg.deadVolume, ...
        'max', cfg.deadVolume + sweptVolume(cfg.posMin, cfg) - excessMl, ...
        'sink', 'SalineVolume')
    struct('key', 'oxygenRatio', ...
        'label', 'Oxygen ratio (STP volume per saline volume)', ...
        'value', cfg.oxygenRatio, 'min', 0, 'max', 4, 'format', '%.2f', ...
        'sink', 'OxygenRatio')
    struct('key', 'oxygenLoadPressure', 'label', 'Oxygen loading pressure', ...
        'kind', 'pressure', 'value', 7, 'min', 2, 'max', 14.6)
    struct('key', 'targetPressure', 'label', 'Target pressure', ...
        'kind', 'pressure', 'value', 100, 'min', cfg.atmAmbient, ...
        'max', min(cfg.pressureMax, cfg.pressureCeiling ...
        - cfg.pressureCeilingHyst) * cfg.atmPerMPa + cfg.atmAmbient)
    struct('key', 'mixTime', 'label', 'Mixing time', 'unit', 's', ...
        'value', 1800, 'min', 0, 'max', 36000, 'format', '%.0f')
    struct('key', 'useMixer', 'label', 'Use Mixer', 'value', 1, ...
        'min', 0, 'max', 1, 'format', '%d')
    };

% ----- Steps -----
steps = {
    struct('section', 'Process parameters', 'type', 'param', ...
        'title', 'Set the process parameters', ...
        'text', ['Enter the saline volume and the oxygen charge (the ' ...
        'positions they give are computed from them), the target ' ...
        'pressure and the mixing time, then confirm.'], ...
        'params', {{'salineVolume', 'oxygenRatio', 'oxygenLoadPressure', ...
        'targetPressure', 'mixTime', 'useMixer'}})

    % Resetting a previous experiment (SOP 7-17)
    struct('section', 'Reset previous experiment', 'type', 'confirm', ...
        'title', 'Is homing required?', ...
        'text', ['Homing is needed only when the position frame is lost: ' ...
        'after an encoder alarm (a drive fault), a controller battery ' ...
        'failure or a controller replacement. Otherwise skip to the flush.'], ...
        'confirmLabel', 'Home the Axis', 'skipTo', 'flushPrepare', ...
        'skipLabel', 'Skip Homing')
    struct('type', 'confirm', 'title', 'Vent the chamber', ...
        'checks', {{'Open the pressure chamber outlet valve', ...
        'Open the delivery valve'}}, 'confirmLabel', 'Continue')
    struct('type', 'confirm', 'title', 'Free the chamber', ...
        'text', ['Press the emergency stop before reaching in. If the ' ...
        'procedure pauses while it is down, carry on; once it is pulled ' ...
        'out, reset any fault and press Resume.'], ...
        'checks', {{'Press the emergency stop', ...
        'Disconnect the white wire connector going up into the chamber', ...
        ['Unscrew the large nut under the pressure chamber and place it ' ...
        'on top of the actuator'], 'Pull out the emergency stop'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Home the axis', ...
        'text', 'Watch the piston and make sure the wires are not pinched.', ...
        'op', 'home')
    struct('type', 'confirm', 'title', 'Check the O-rings', ...
        'checks', {{['If there are O-rings on the syringe, they are ' ...
        'concentric with the syringe opening']}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Return the piston into the chamber', ...
        'op', 'position', 'unit', 'mm', 'target', 0)
    struct('type', 'confirm', 'title', 'Secure the chamber', ...
        'checks', {{'Tighten the large nut hand tight', ...
        'Reconnect the white wire connector'}}, 'confirmLabel', 'Continue')

    % Flushing the compression chamber (SOP 18-31)
    struct('id', 'flushPrepare', 'section', 'Flush the chamber', ...
        'type', 'confirm', 'title', 'Prepare the flush', ...
        'checks', {{'Close all valves', ...
        'Pull the cut IV tubing off the 3-way stopcock', ...
        'Turn the stopcock''s blue dial toward the capped outlet', ...
        'Open the saline inlet valve'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Empty the chamber', ...
        'text', 'Moving the piston to the end of travel.', ...
        'op', 'position', 'unit', 'mm', 'target', 0, ...
        'pressureMax', SALINE_PUSH_MAX)
    struct('type', 'confirm', 'title', 'Connect a fresh saline bag', ...
        'checks', {{'Waste container (100 mL or more) at hand', ...
        'Roll the roller clamp to the far end (closed)', ...
        ['Insert the IV spike through the longer tube of the bag until ' ...
        'it is pierced'], 'Hang the saline bag on the stand', ...
        'Connect the IV tubing to the 3-way stopcock', ...
        'Squeeze the bladder on the IV spike to start the flow'}}, ...
        'confirmLabel', 'Continue')
    struct('id', 'flushCycle', 'type', 'confirm', 'title', 'Open the saline line', ...
        'checks', {{'Open the roller clamp', 'Saline inlet valve open'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw saline', ...
        'text', sprintf('Drawing saline to %g mm from the end of travel.', ...
        FLUSH_DRAW), 'op', 'position', 'unit', 'mm', 'target', FLUSH_DRAW)
    struct('type', 'confirm', 'title', 'Switch the stopcock to its outlet', ...
        'checks', {{['Flow into the bladder has stopped and the pressure ' ...
        'reads about 1 atm'], 'Close the roller clamp', ...
        'Turn the blue knob to block the line to the saline bag', ...
        'Remove the cap from the stopcock''s other outlet', ...
        'Hold the waste container under the open outlet'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Push the saline out', ...
        'text', sprintf('Pushing to the end of travel at %g mm/s.', PUSH_SPEED), ...
        'op', 'position', 'unit', 'mm', 'target', 0, 'speed', PUSH_SPEED, ...
        'pressureMax', SALINE_PUSH_MAX)
    struct('type', 'confirm', 'title', 'Flush again or go on', ...
        'checks', {{'Put the cap back on the stopcock outlet', ...
        'Turn the blue knob back to block that outlet'}}, ...
        'repeatFrom', 'flushCycle', 'repeatLabel', 'Flush Again', ...
        'confirmLabel', 'Done Flushing')

    % Preparing the outlet hose (SOP 32-45)
    struct('id', 'hoseDraw', 'section', 'Prepare the outlet hose', ...
        'type', 'confirm', 'title', 'Prepare the hose fill', ...
        'checks', {{'Close the pressure chamber outlet valve', ...
        'Close the delivery valve', 'Saline inlet valve open', ...
        'Open the roller clamp'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw saline for the hose', ...
        'text', sprintf('Drawing saline to %g mm from the end of travel.', ...
        HOSE_DRAW), 'op', 'position', 'unit', 'mm', 'target', HOSE_DRAW)
    struct('type', 'confirm', 'title', 'Close the saline line', ...
        'checks', {{['Flow into the bladder has stopped and the pressure ' ...
        'reads about 1 atm'], 'Close the roller clamp', ...
        'Close the saline inlet valve', 'Open the delivery valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'confirm', 'title', 'Ready the hose', ...
        'checks', {{['Hold the hose horizontal, no part of it lower than ' ...
        'where it leaves the chamber'], ...
        'Hold the waste beaker under the needle', ...
        'Open the pressure chamber outlet valve'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Fill the hose', ...
        'text', sprintf(['Pushing at %g mm/s. Press Saline at Needle as ' ...
        'soon as saline comes out of the needle.'], PUSH_SPEED), ...
        'op', 'position', 'unit', 'mm', 'target', 0, 'speed', PUSH_SPEED, ...
        'until', 'confirm', 'confirmLabel', 'Saline at Needle', ...
        'pressureMax', HOSE_PUSH_MAX)
    struct('type', 'confirm', 'title', 'Close the hose', ...
        'text', ['If the piston reached the end of travel before saline ' ...
        'came out, close the valves and draw again.'], ...
        'checks', {{'Close the delivery valve', ...
        'Close the pressure chamber outlet valve'}}, ...
        'repeatFrom', 'hoseDraw', 'repeatLabel', 'Draw Again', ...
        'confirmLabel', 'Continue')

    % Saline fill (SOP 46-55)
    struct('section', 'Saline fill', 'type', 'confirm', ...
        'title', 'Open the saline line', ...
        'checks', {{'Open the roller clamp', 'Open the saline inlet valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw the fill', ...
        'text', sprintf('Drawing {salineVolume} mL plus %g mm to push back.', ...
        EXCESS_MM), 'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) salineDrawVolume(v, c, EXCESS_MM))
    struct('type', 'confirm', 'title', 'Switch the stopcock to its outlet', ...
        'checks', {{['Flow into the bladder has stopped and the pressure ' ...
        'reads about 1 atm'], 'Close the roller clamp', ...
        ['Turn the stopcock toward the other outlet and remove the cap ' ...
        'from it'], 'Hold the waste container under the open outlet'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Push back to the fill volume', ...
        'op', 'position', 'unit', 'mL', 'target', 'salineVolume', ...
        'speed', PUSH_SPEED, 'pressureMax', SALINE_PUSH_MAX)
    struct('type', 'confirm', 'title', 'Close the saline line', ...
        'checks', {{['Turn the stopcock dial back to close the outlet and ' ...
        'put the cap back on'], 'Close the saline inlet valve'}}, ...
        'confirmLabel', 'Continue')

    % Oxygen fill (SOP 56-61)
    struct('section', 'Oxygen fill', 'type', 'machine', ...
        'title', 'Retract past the oxygen position', ...
        'text', sprintf(['Retracting %g mm past the chamber volume for ' ...
        '{oxygenRatio} volumes of oxygen at {oxygenLoadPressure}.'], EXCESS_MM), ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) oxygenFillVolume(v, c, EXCESS_MM) + EXCESS_MM * mLPerMm(c))
    struct('type', 'machine', 'title', 'Come back to the oxygen position', ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) oxygenFillVolume(v, c, EXCESS_MM))
    struct('type', 'confirm', 'title', 'Connect the oxygen', ...
        'text', ['If the oxygen tube is disconnected: open the regulator ' ...
        'until oxygen flows (cover the end of the tube; it hisses when ' ...
        'uncovered), attach the tube to the hose barb on the oxygen inlet ' ...
        'valve and tighten the hose clamp with a screwdriver or wrench.'], ...
        'checks', {{'Oxygen tube attached and clamped on the oxygen inlet valve', ...
        'Open the oxygen inlet valve', ...
        ['Open the regulator (counter-clockwise) until the pressure ' ...
        'readout shows about {oxygenLoadPressure}']}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'param', 'title', 'Enter the loading pressure', ...
        'text', ['Enter the pressure the readout shows. The piston then ' ...
        'moves to hold the oxygen charge at that pressure.'], ...
        'params', {{'oxygenLoadPressure'}})
    struct('type', 'machine', 'title', 'Adjust for the loading pressure', ...
        'text', ['Moving to the chamber volume for {oxygenRatio} volumes ' ...
        'of oxygen at {oxygenLoadPressure}.'], ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) oxygenFillVolume(v, c, 0))
    struct('type', 'confirm', 'title', 'Close the oxygen', ...
        'checks', {{'Close the oxygen inlet valve', ...
        'Close the oxygen regulator (clockwise until it stops)'}}, ...
        'confirmLabel', 'Continue')

    % Pressurize and mix (SOP 62-64)
    struct('section', 'Pressurize and mix', 'type', 'confirm', ...
        'title', 'Ensure all valves are closed')
    struct('type', 'machine', 'title', 'Pressurize', ...
        'text', 'Holding {targetPressure}.', 'op', 'pressure', ...
        'target', 'targetPressure', 'until', 'running', 'keep', true, ...
        'timerStart', true)
    struct('type', 'wait', 'title', 'Mixing', ...
        'text', 'Mixing at {targetPressure} for {mixTime} s.', ...
        'duration', 'mixTime', 'mixer', 'useMixer', 'record', 10)

    % Discharge (SOP 65-68)
    struct('section', 'Discharge', 'type', 'confirm', ...
        'title', 'Open the pressure chamber outlet valve', ...
        'text', ['SLOWLY crack open the pressure chamber outlet valve until ' ...
        'the pressure dips and recovers.'], ...
        'checks', {{'Pressure chamber outlet valve open, pressure recovered'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'confirm', 'title', 'Purge the hose', ...
        'text', ['Hold the needle over a waste container. Open the delivery ' ...
        'valve for the time given by the spreadsheet, or until oxygenated ' ...
        'saline comes through, then close it. Volume discharged shows what ' ...
        'has left the chamber.'], 'zeroVolume', true, ...
        'checks', {{'Hose purged and the delivery valve closed'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'confirm', 'title', 'Deliver', ...
        'text', ['When ready to output into the system, open the delivery ' ...
        'valve. Confirm when the delivery is complete; the step also ends ' ...
        'at the end of travel.'], ...
        'zeroVolume', true, 'alsoWhen', 'endOfTravel', ...
        'confirmLabel', 'Delivery Complete')

    % Clean up (SOP 69-80)
    struct('section', 'Clean up', 'type', 'confirm', ...
        'title', 'Discharge the remainder', ...
        'text', ['Hold the needle over a waste container, open the delivery ' ...
        'valve and wait until oxygenated saline stops coming out; the step ' ...
        'also ends at the end of travel.'], ...
        'alsoWhen', 'endOfTravel', 'confirmLabel', 'Discharge Complete')
    struct('type', 'machine', 'title', 'End pressure control', ...
        'op', 'stop', 'timerStop', true, 'mixer', 'off')
    struct('type', 'machine', 'title', 'Push out what is left', ...
        'text', 'Moving to the end of travel with the needle over the waste.', ...
        'op', 'position', 'unit', 'mm', 'target', 0)
    struct('type', 'confirm', 'title', 'Set up the rinse', ...
        'checks', {{['Close the delivery valve and the pressure chamber ' ...
        'outlet valve'], ...
        'Close the roller clamp (roll it to the far end)', ...
        'Disconnect the saline line from the 3-way stopcock', ...
        ['Connect the loose IV tubing to the stopcock, its other end in a ' ...
        'beaker of deionized water'], 'Open the saline inlet valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw the rinse water', ...
        'text', sprintf(['Drawing at %g mm/s. Press Water Drawn when most ' ...
        'of the water is in; the draw stops at %g mm from the end of ' ...
        'travel.'], PUSH_SPEED, RINSE_LIMIT), ...
        'op', 'position', 'unit', 'mm', 'target', RINSE_LIMIT, ...
        'speed', PUSH_SPEED, 'until', 'confirm', 'confirmLabel', 'Water Drawn')
    struct('type', 'confirm', 'title', 'Open the outlet', ...
        'checks', {{'Close the saline inlet valve', ...
        'Open the pressure chamber outlet valve', 'Open the delivery valve', ...
        'Hold the needle over the waste container'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Push the rinse out', ...
        'text', sprintf('Pressure control at %g atm absolute.', RINSE_PRESSURE), ...
        'op', 'pressure', 'target', RINSE_PRESSURE, 'until', 'running', ...
        'keep', true)
    struct('type', 'confirm', 'title', 'Wait for the discharge to stop', ...
        'text', 'The step also ends at the end of travel.', ...
        'alsoWhen', 'endOfTravel', 'confirmLabel', 'Discharge Stopped')
    struct('type', 'machine', 'title', 'End the rinse', 'op', 'stop')
    };

proc = struct('name', 'SOS Gen 3 Compressor SOP', ...
    'params', {params}, 'steps', {steps}, ...
    'timerLabel', 'Time pressurized', ...
    'volumeLabel', 'Volume discharged (mL)');
end

function V = salineDrawVolume(v, c, excessMm)
% Chamber volume of the saline draw, mL: the fill plus excessMm of travel,
% pushed back out of the stopcock afterwards. The oxygen fill is checked
% here too, so a charge the chamber cannot hold stops the run before any
% saline is drawn.
oxygenFillVolume(v, c, excessMm);
V = v.salineVolume + excessMm * mLPerMm(c);
end

function V = oxygenFillVolume(v, c, excessMm)
% Chamber volume for the oxygen fill, mL.
%   V = Vs + r * Vs * (P_STP / P_load) * (T_room / T_STP)     [mL]
% Vs [mL] salineVolume (saline incl. dead volume), r [-] oxygenRatio (STP
% volume per saline volume, STP = 0 degC and 1 atm), P_load [atm abs]
% oxygenLoadPressure, P_STP = 1 atm, T_room = 293.15 K, T_STP = 273.15 K.
% Ideal gas, isothermal at room temperature; dissolution of oxygen in the
% saline during the load is ignored (it only adds to the charge). V plus
% excessMm of travel (the retract past it) must fit in the chamber.
P_STP = 1;           % atm
T_ROOM = 293.15;     % K
T_STP = 273.15;      % K
V = v.salineVolume + v.oxygenRatio * v.salineVolume ...
    * (P_STP / v.oxygenLoadPressure) * (T_ROOM / T_STP);
vMax = c.deadVolume + sweptVolume(c.posMin, c);
need = V + excessMm * mLPerMm(c);
if need > vMax
    error('sopProcedure:oxygenFill', ['the oxygen fill needs %.0f mL, ' ...
        'more than the chamber holds (%.0f mL)'], need, vMax);
end
end
