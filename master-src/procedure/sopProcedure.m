function proc = sopProcedure()
%SOPPROCEDURE The procedure the operator app walks through in non-manual mode.
%   proc = sopProcedure()
%
%   Data only; the engine (master-src/logic/proc*.m) holds no procedure of
%   its own. To use another procedure, edit this file or add a file beside
%   it and set cfg.procedure in masterConfig.m. procNew validates the
%   result; tests/smokeProcedureEngine.m runs it through procNew and walks
%   it.
%
%   The machine. Three valves open onto the chamber: the oxygen inlet valve
%   (from the regulator on the oxygen cylinder), the saline inlet valve and
%   the proximal valve. The saline inlet valve is fed by a 3-way stopcock
%   whose other two ports go to the saline bag (through the IV line and its
%   roller clamp) and to a capped dump outlet. The proximal valve opens
%   onto the hose; the distal valve at its far end opens onto the needle
%   (the orifice plate), which sets the flow out. The operator works every
%   valve; the procedure moves the piston, holds the pressure and decides
%   when a draw has filled, a volume has passed or the piston has reached
%   the end of travel.
%
%   The run, section by section:
%     Reset         Homing, only when the position frame is lost; the
%                   first step offers to skip it. The chamber is vented,
%                   unbolted and the piston homed out of it and returned.
%     Flush         The chamber is emptied out of the stopcock, then
%                   flushed in cycles: a 20 mm saline draw, a wait for the
%                   inflow to stop (the pressure back at ambient), a push
%                   out of the dump outlet. The operator repeats the cycle.
%     Hose          A saline draw, then the hose is filled through the
%                   needle under pressure control (the orifices limit the
%                   flow) until the hose volume has passed.
%     Saline fill   The saline volume plus 5 mm is drawn, then the 5 mm is
%                   pushed back out of the dump outlet, so the fill ends on
%                   a move toward the end of travel.
%     Oxygen fill   With every valve shut the piston retracts 5 mm past
%                   the volume that holds the oxygen charge at the planned
%                   loading pressure and comes back to it. The operator
%                   opens the oxygen inlet valve and raises the regulator;
%                   the pressure reading is taken as the loading pressure
%                   and the piston moves to the volume for it.
%     Pressurize    Pressure control at the target, then the mixing time
%                   with the mixer on.
%     Discharge     The operator cracks the proximal valve open; once the
%                   pressure has recovered, the distal valve is opened
%                   until the purge volume has passed (the hose's virgin
%                   saline), closed, and opened again to deliver.
%     Clean up      The remainder is discharged to the end of travel, the
%                   chamber rinsed with deionized water drawn through the
%                   stopcock and pushed out through the hose under pressure
%                   control.
%   The saline volume and the oxygen ratio are also written to the shell's
%   SalineVolume and OxygenRatio blocks (sinks), which the trace records.
%
%   See the "Procedure (non-manual mode)" section of master-src/README.md
%   for the fields of a parameter and of a step.

cfg = masterConfig();

% ----- Constants -----
EXCESS_MM = 5;              % mm drawn past a fill position and pushed back
PUSH_SPEED = 2;             % mm/s of a push out of the stopcock (6.9 mL/s)
PUSH_GUARD = cfg.atmAmbient + 0.5;  % atm absolute: a push out of the stopcock pauses above this (the outlet is blocked)
PUSH_PRESSURE = 100;        % atm absolute of the pushes through the hose (hose fill, rinse); the orifices set the flow
FLUSH_DRAW = 20;            % mm from the end of travel of a flush draw
HOSE_DRAW = 30;             % mm from the end of travel of the draw that fills the hose
HOSE_VOLUME = 58;           % mL from the proximal valve to the orifices (6 ft hose of 1/4 in bore, and the tube)
HOSE_FILL = HOSE_VOLUME + 5;  % mL pushed through the hose to fill it
RINSE_MAX_MM = 150;         % mm from the end of travel, the deepest rinse draw
SETTLE_TOL = 0.2;           % atm: a draw has filled when the pressure is this close to ambient ...
SETTLE_TIME = 3;            % s ... for this long
SETTLE_TIMEOUT = 120;       % s before a draw that does not fill pauses (bag empty, clamp shut)
RECOVER_TOL = 1;            % atm about the target: the pressure has recovered from the proximal valve's opening

% ----- Parameters (Process Parameters tab) -----
k = mLPerMm(cfg);
params = {
    struct('key', 'salineVolume', ...
        'label', 'Saline volume (chamber, incl. dead volume)', ...
        'unit', 'mL', 'value', cfg.salineVolume, 'min', cfg.deadVolume, ...
        'max', cfg.deadVolume + sweptVolume(cfg.posMin, cfg) - EXCESS_MM * k, ...
        'sink', 'SalineVolume')
    struct('key', 'oxygenRatio', ...
        'label', 'Oxygen ratio (STP volume per saline volume)', ...
        'value', cfg.oxygenRatio, 'min', 0, 'max', 4, 'format', '%.2f', ...
        'sink', 'OxygenRatio')
    struct('key', 'oxygenLoadPressure', ...
        'label', 'Oxygen loading pressure (planned)', ...
        'kind', 'pressure', 'value', 7, 'min', 2, 'max', 14.6)
    struct('key', 'targetPressure', 'label', 'Target pressure', ...
        'kind', 'pressure', 'value', 100, 'min', cfg.atmAmbient, ...
        'max', min(cfg.pressureMax, cfg.pressureCeiling ...
        - cfg.pressureCeilingHyst) * cfg.atmPerMPa + cfg.atmAmbient)
    struct('key', 'mixTime', 'label', 'Mixing time', 'unit', 's', ...
        'value', 1800, 'min', 0, 'max', 36000, 'format', '%.0f')
    struct('key', 'useMixer', 'label', 'Use Mixer', 'value', 1, ...
        'min', 0, 'max', 1, 'format', '%d')
    % The purge carries the hose's virgin saline and the slug that degassed
    % entering the hose when the proximal valve opened.
    struct('key', 'purgeVolume', 'label', 'Hose purge volume', ...
        'unit', 'mL', 'value', HOSE_VOLUME + 6, 'min', 1, 'max', 200, ...
        'format', '%.0f')
    struct('key', 'rinseVolume', 'label', 'Rinse water volume', ...
        'unit', 'mL', 'value', 250, 'min', 10, 'max', RINSE_MAX_MM * k, ...
        'format', '%.0f')
    };

% A wait for a draw to fill: the inflow stops when the chamber is back at
% the saline bag's pressure, about ambient.
drawFilled = @(title) struct('type', 'wait', 'title', title, ...
    'text', 'Waiting for the inflow to stop (the pressure back at ambient).', ...
    'until', 'settled', 'target', cfg.atmAmbient, 'tolerance', SETTLE_TOL, ...
    'duration', SETTLE_TIME, 'timeout', SETTLE_TIMEOUT);

% ----- Steps -----
steps = {
    struct('section', 'Process parameters', 'type', 'param', ...
        'title', 'Set the process parameters', ...
        'params', {{'salineVolume', 'oxygenRatio', 'oxygenLoadPressure', ...
        'targetPressure', 'mixTime', 'useMixer', 'purgeVolume', 'rinseVolume'}})

    % ===== Reset: homing, skipped unless the position frame is lost =====
    struct('section', 'Reset', 'type', 'confirm', ...
        'title', 'Is homing required?', ...
        'text', 'Skip unless the axis needs homing.', ...
        'confirmLabel', 'Home the Axis', 'skipTo', 'flushPrepare', ...
        'skipLabel', 'Skip Homing')
    % The piston leaves the cylinder, so the chamber is vented (the exit
    % guard faults a retract under pressure) and unbolted from the
    % actuator, with the emergency stop down while the operator reaches in.
    struct('type', 'confirm', 'title', 'Vent and free the chamber', ...
        'text', ['If the procedure pauses while the emergency stop is down, ' ...
        'carry on; once it is pulled out, reset any fault and press Resume.'], ...
        'checks', {{'Open the proximal and distal valves', ...
        'Press the emergency stop', ...
        'Disconnect the white wire connector to the chamber', ...
        'Unscrew the large nut under the chamber and rest it on the actuator', ...
        'Pull out the emergency stop'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Home the axis', ...
        'text', 'Watch the piston and make sure the wires are not pinched.', ...
        'op', 'home')
    struct('type', 'confirm', 'title', 'Check the O-rings', ...
        'checks', {{'O-rings on the syringe (if any) concentric with its opening'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Return the piston into the chamber', ...
        'op', 'position', 'unit', 'mm', 'target', 0)
    struct('type', 'confirm', 'title', 'Secure the chamber', ...
        'checks', {{'Tighten the large nut hand tight', ...
        'Reconnect the white wire connector'}}, 'confirmLabel', 'Continue')

    % ===== Flush: saline drawn in and pushed out of the dump outlet =====
    % The chamber is first emptied through the stopcock's open bag port,
    % the dump outlet blocked.
    struct('id', 'flushPrepare', 'section', 'Flush', 'type', 'confirm', ...
        'title', 'Prepare the flush', ...
        'checks', {{'Close all valves', ...
        'Remove the cut IV tubing from the stopcock', ...
        'Stopcock blocking the capped dump outlet', ...
        'Open the saline inlet valve', ...
        'Waste container under the stopcock'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Empty the chamber', ...
        'op', 'position', 'unit', 'mm', 'target', 0, 'speed', PUSH_SPEED, ...
        'pressureMax', PUSH_GUARD)
    struct('type', 'confirm', 'title', 'Connect the saline bag', ...
        'checks', {{'Fresh saline bag spiked and hung, roller clamp closed', ...
        'IV line connected to the stopcock', ...
        'Bladder on the spike squeezed to start the flow'}}, ...
        'confirmLabel', 'Continue')
    struct('id', 'flushCycle', 'type', 'confirm', 'title', 'Open the saline line', ...
        'checks', {{'Open the roller clamp', 'Saline inlet valve open'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw saline', ...
        'op', 'position', 'unit', 'mm', 'target', FLUSH_DRAW)
    drawFilled('Saline filling')
    struct('type', 'confirm', 'title', 'Switch the stopcock to the dump outlet', ...
        'checks', {{'Close the roller clamp', ...
        'Turn the stopcock to block the saline bag line', ...
        'Uncap the dump outlet, waste container under it'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Push the saline out', ...
        'op', 'position', 'unit', 'mm', 'target', 0, 'speed', PUSH_SPEED, ...
        'pressureMax', PUSH_GUARD)
    struct('type', 'confirm', 'title', 'Flush again or go on', ...
        'checks', {{'Cap the dump outlet and turn the stopcock back to block it'}}, ...
        'repeatFrom', 'flushCycle', 'repeatLabel', 'Flush Again', ...
        'confirmLabel', 'Done Flushing')

    % ===== Hose: filled with saline through the needle =====
    % The orifices pass about 4.8 mL/s at 10 MPa, so a push at the stopcock
    % speed would exceed the pressure ceiling: the fill runs under pressure
    % control, the orifices setting the flow, until the hose volume has
    % left the chamber.
    struct('id', 'hoseDraw', 'section', 'Hose', 'type', 'confirm', ...
        'title', 'Prepare the hose fill', ...
        'checks', {{'Proximal and distal valves closed', ...
        'Open the roller clamp', 'Saline inlet valve open'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw saline for the hose', ...
        'op', 'position', 'unit', 'mm', 'target', HOSE_DRAW)
    drawFilled('Saline filling')
    struct('type', 'confirm', 'title', 'Open the hose', ...
        'checks', {{'Close the roller clamp and the saline inlet valve', ...
        'Open the distal valve, then the proximal valve', ...
        ['Hose held horizontal, no lower than where it leaves the ' ...
        'chamber, the needle over the waste beaker']}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Fill the hose', ...
        'text', sprintf('Pressure control at %g atm absolute.', PUSH_PRESSURE), ...
        'op', 'pressure', 'target', PUSH_PRESSURE, 'until', 'running', ...
        'keep', true, 'zeroVolume', true)
    struct('type', 'wait', 'title', 'Filling the hose', ...
        'until', 'volume', 'volume', HOSE_FILL)
    struct('type', 'machine', 'title', 'End pressure control', 'op', 'stop')
    struct('type', 'confirm', 'title', 'Close the hose', ...
        'text', 'If saline did not reach the needle, fill again.', ...
        'checks', {{'Close the distal valve', 'Close the proximal valve'}}, ...
        'repeatFrom', 'hoseDraw', 'repeatLabel', 'Fill Again', ...
        'confirmLabel', 'Continue')

    % ===== Saline fill: the volume plus 5 mm, the 5 mm pushed back =====
    struct('section', 'Saline fill', 'type', 'confirm', ...
        'title', 'Open the saline line', ...
        'checks', {{'Open the roller clamp', 'Open the saline inlet valve'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw the fill', ...
        'text', sprintf('Drawing {salineVolume} mL plus %g mm.', EXCESS_MM), ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) salineDrawVolume(v, c, EXCESS_MM))
    drawFilled('Saline filling')
    struct('type', 'confirm', 'title', 'Switch the stopcock to the dump outlet', ...
        'checks', {{'Close the roller clamp', ...
        'Turn the stopcock to block the saline bag line', ...
        'Uncap the dump outlet, waste container under it'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Push back to the fill volume', ...
        'op', 'position', 'unit', 'mL', 'target', 'salineVolume', ...
        'speed', PUSH_SPEED, 'pressureMax', PUSH_GUARD)
    struct('type', 'confirm', 'title', 'Close the saline line', ...
        'checks', {{'Cap the dump outlet and turn the stopcock back to block it', ...
        'Close the saline inlet valve'}}, 'confirmLabel', 'Continue')

    % ===== Oxygen fill: the charge loaded at the regulator's pressure =====
    % Moving 5 mm past the position and back approaches it, like the
    % fill, on a move toward the end of travel.
    struct('section', 'Oxygen fill', 'type', 'machine', ...
        'title', 'Retract past the oxygen position', ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) oxygenFillVolume(v, c, EXCESS_MM) + EXCESS_MM * mLPerMm(c))
    struct('type', 'machine', 'title', 'Come back to the oxygen position', ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) oxygenFillVolume(v, c, EXCESS_MM))
    % The line from the regulator holds whatever pressure the regulator was
    % left at, so every other valve is shut before the oxygen inlet opens.
    struct('type', 'confirm', 'title', 'Open the oxygen', ...
        'text', ['If the oxygen tube is disconnected: open the regulator ' ...
        'until oxygen flows from the tube, attach it to the hose barb on ' ...
        'the oxygen inlet valve and tighten the clamp.'], ...
        'checks', {{'Saline inlet, proximal and distal valves closed', ...
        'Oxygen tube clamped on the oxygen inlet valve', ...
        'Open the oxygen inlet valve'}}, 'confirmLabel', 'Continue')
    % The reading on confirm becomes oxygenLoadPressure, and the next move
    % sets the volume for it with the regulator still feeding the chamber.
    struct('type', 'confirm', 'title', 'Set the loading pressure', ...
        'text', ['Turn the regulator clockwise until the pressure reads ' ...
        'about {oxygenLoadPressure}. Confirm once it is steady: the ' ...
        'reading is taken as the loading pressure.'], ...
        'capture', 'oxygenLoadPressure', 'confirmLabel', 'Take Reading')
    struct('type', 'machine', 'title', 'Adjust for the loading pressure', ...
        'text', 'Moving to the volume for {oxygenRatio} volumes at {oxygenLoadPressure}.', ...
        'op', 'position', 'unit', 'mL', ...
        'target', @(v, c) oxygenFillVolume(v, c, 0))
    struct('type', 'confirm', 'title', 'Close the oxygen', ...
        'checks', {{'Close the oxygen inlet valve', ...
        'Turn the regulator counter-clockwise to close it', ...
        'All valves closed'}}, 'confirmLabel', 'Continue')

    % ===== Pressurize and mix =====
    struct('section', 'Pressurize and mix', 'type', 'machine', ...
        'title', 'Pressurize', 'text', 'Holding {targetPressure}.', ...
        'op', 'pressure', 'target', 'targetPressure', 'until', 'running', ...
        'keep', true, 'timerStart', true)
    struct('type', 'wait', 'title', 'Mixing', ...
        'duration', 'mixTime', 'mixer', 'useMixer', 'record', 10)

    % ===== Discharge =====
    % Cracking the proximal valve fills the hose's compliance from the
    % chamber; opened slowly the dip stays small, and the loop restores the
    % target before the purge starts.
    struct('section', 'Discharge', 'type', 'confirm', ...
        'title', 'Crack the proximal valve', ...
        'text', 'SLOWLY open the proximal valve and stop as soon as it cracks.', ...
        'checks', {{'Proximal valve cracked open'}}, 'confirmLabel', 'Continue')
    struct('type', 'wait', 'title', 'Pressure recovering', ...
        'until', 'settled', 'tolerance', RECOVER_TOL, 'duration', 2)
    struct('type', 'confirm', 'title', 'Purge the hose', ...
        'text', 'The procedure says when {purgeVolume} mL have passed.', ...
        'checks', {{'Needle over the waste container', ...
        'Open the distal valve'}}, 'zeroVolume', true, ...
        'confirmLabel', 'Continue')
    struct('type', 'wait', 'title', 'Purging the hose', ...
        'until', 'volume', 'volume', 'purgeVolume')
    struct('type', 'confirm', 'title', 'Close the distal valve', ...
        'checks', {{'Close the distal valve'}}, 'confirmLabel', 'Continue')
    struct('type', 'confirm', 'title', 'Deliver', ...
        'text', ['Open the distal valve to deliver into the system. Confirm ' ...
        'when the delivery is complete; the step also ends at the end of ' ...
        'travel.'], 'zeroVolume', true, 'alsoWhen', 'endOfTravel', ...
        'confirmLabel', 'Delivery Complete')

    % ===== Clean up =====
    struct('section', 'Clean up', 'type', 'confirm', ...
        'title', 'Discharge the remainder', ...
        'checks', {{'Needle over the waste container', 'Distal valve open'}}, ...
        'confirmLabel', 'Continue')
    struct('type', 'wait', 'title', 'Discharging to the end of travel', ...
        'until', 'endOfTravel')
    % Pressure control stops short of the end of travel by its end margin;
    % the position move takes the piston the rest of the way.
    struct('type', 'machine', 'title', 'End pressure control', ...
        'op', 'stop', 'timerStop', true, 'mixer', 'off')
    struct('type', 'machine', 'title', 'Push out what is left', ...
        'op', 'position', 'unit', 'mm', 'target', 0)
    struct('type', 'confirm', 'title', 'Set up the rinse', ...
        'checks', {{'Close the distal and proximal valves', ...
        'Close the roller clamp', ...
        'Disconnect the saline line from the stopcock', ...
        ['Connect the loose IV tubing to the stopcock, its end in at least ' ...
        '{rinseVolume} mL of deionized water'], ...
        'Open the saline inlet valve'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Draw the rinse water', ...
        'text', 'Drawing {rinseVolume} mL.', ...
        'op', 'position', 'unit', 'mL', 'speed', PUSH_SPEED, ...
        'target', @(v, c) c.deadVolume + v.rinseVolume)
    struct('type', 'confirm', 'title', 'Open the outlet', ...
        'checks', {{'Close the saline inlet valve', ...
        'Open the proximal and distal valves', ...
        'Needle over the waste container'}}, 'confirmLabel', 'Continue')
    struct('type', 'machine', 'title', 'Push the rinse out', ...
        'text', sprintf('Pressure control at %g atm absolute.', PUSH_PRESSURE), ...
        'op', 'pressure', 'target', PUSH_PRESSURE, 'until', 'running', ...
        'keep', true)
    struct('type', 'wait', 'title', 'Discharging to the end of travel', ...
        'until', 'endOfTravel')
    struct('type', 'machine', 'title', 'End the rinse', 'op', 'stop')
    };

proc = struct('name', 'SOS fill, mix and delivery', ...
    'params', {params}, 'steps', {steps}, ...
    'timerLabel', 'Time pressurized', ...
    'volumeLabel', 'Volume discharged (mL)');
end

function V = salineDrawVolume(v, c, excessMm)
% Chamber volume of the saline draw, mL: the fill plus excessMm of travel,
% pushed back out of the stopcock afterwards. The oxygen fill is checked
% here too, so a charge the chamber cannot hold stops the run before any
% saline is drawn.
oxygenFillVolume(v, c, excessMm);
V = v.salineVolume + excessMm * mLPerMm(c);
end

function V = oxygenFillVolume(v, c, excessMm)
% Chamber volume for the oxygen fill, mL.
%   V = Vs + r * Vs * (P_STP / P_load) * (T_room / T_STP)     [mL]
% Vs [mL] salineVolume (saline incl. dead volume), r [-] oxygenRatio (STP
% volume per saline volume, STP = 0 degC and 1 atm), P_load [atm abs]
% oxygenLoadPressure, P_STP = 1 atm, T_room = 293.15 K, T_STP = 273.15 K.
% Ideal gas, isothermal at room temperature; dissolution of oxygen in the
% saline during the load is ignored (it only adds to the charge). V plus
% excessMm of travel (the retract past it) must fit in the chamber.
P_STP = 1;           % atm
T_ROOM = 293.15;     % K
T_STP = 273.15;      % K
V = v.salineVolume + v.oxygenRatio * v.salineVolume ...
    * (P_STP / v.oxygenLoadPressure) * (T_ROOM / T_STP);
vMax = c.deadVolume + sweptVolume(c.posMin, c);
need = V + excessMm * mLPerMm(c);
if need > vMax
    error('sopProcedure:oxygenFill', ['the oxygen fill needs %.0f mL, ' ...
        'more than the chamber holds (%.0f mL)'], need, vMax);
end
end
