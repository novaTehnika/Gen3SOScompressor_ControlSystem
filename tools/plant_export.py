#!/usr/bin/env python3
"""Write the simulated slave's plant parameters and initial state from the
design model.

    python3 tools/plant_export.py slave-sim/generated-c/plant_defaults.h

The simulated slave's chamber, outlet and drive are the C port of the
design model's Plant (slave-sim/c/plant.c). This constructs that Plant in
Python, with the default Params and the simulator's scenario, and writes
what plant_init takes: the parameters named in PLANT_PARAMS of
slave-sim/c/plant.h, the initial state, the cylinder volume at x = 0 and
the hose state. So the values, and the formulas that derive them, have
one source: design/pressure-loop.

The simulator's scenario is a run's start: the 1:1 oxygen charge admitted
at the supply pressure, Params.Vl0 of saline, and the hose open (part of
the chamber), so that outflow can leave through it.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'design' / 'pressure-loop'))
from params import Params          # noqa: E402
from plant import Plant            # noqa: E402
from scenarios import Scenario     # noqa: E402


def main(out):
    par = Params()
    sc = Scenario('slave-sim', T=0.0, tEvent=0.0, P0=par.P_supply, ratio=par.ratio,
                  hose_open0=True)
    pl = Plant(par, sc, 'V')
    header = (ROOT / 'slave-sim' / 'c' / 'plant.h').read_text()
    block = re.search(r'#define PLANT_PARAMS\(X\)(.*?)\n\n', header, re.S).group(1)
    names = re.findall(r'X\((\w+)\)', block)
    special = {'heun': 1.0 if par.solver == 'heun' else 0.0, 'n_dead': len(pl.cmd_queue)}
    lines = ['/* Generated by tools/plant_export.py from design/pressure-loop - do not edit. */',
             '#include "plant.h"', '',
             'static const plant_par_t plant_default_par = {']
    for n in names:
        v = special[n] if n in special else float(getattr(pl, n))
        lines.append(f'    .{n} = {v!r},')
    lines += ['};', '',
              'static const double plant_default_y0[PLANT_N_STATES] = {'
              + ', '.join(repr(float(v)) for v in pl.y) + '};',
              f'static const double plant_default_Vch0 = {pl.Vch0!r};',
              f'static const bool plant_default_hose_open = {"true" if pl.hose_open else "false"};',
              '']
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text('\n'.join(lines))
    return 0


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1]))
